api_menu() {
  need_root || return
  have_aio || { err "AioSocks is not installed"; pause; return; }
  while true; do
    clear
    local cur_host="127.0.0.1"
    [[ -f "$API_HOST_CFG" ]] && cur_host=$(cat "$API_HOST_CFG")
    printf '%b\n' "${W}=== HTTP API ===${N}"
    printf '%b\n' "  Bind host: ${C}${cur_host}${N}"
    echo
    echo "  1) Start API (systemd)"
    echo "  2) Stop API"
    echo "  3) Status"
    echo "  4) Show token"
    echo "  5) Test /api/status"
    echo "  6) Change bind host (127.0.0.1 / 0.0.0.0)"
    echo "  0) Back"
    echo
    read -rp "  Choice: " c
    case "$c" in
      1) "$(xp_bin)" api start --host "$cur_host" && ok "API started on ${cur_host}."; pause ;;
      2) "$(xp_bin)" api stop; pause ;;
      3) "$(xp_bin)" api status; pause ;;
      4) [[ -f /etc/psiphon/api-token ]] && cat /etc/psiphon/api-token || warn "Token not found"; pause ;;
      5)
        local tok; tok=$(cat /etc/psiphon/api-token 2>/dev/null)
        [[ -z "$tok" ]] && { warn "Token not found"; pause; continue; }
        local host="$cur_host"; [[ "$host" == "0.0.0.0" ]] && host="127.0.0.1"
        local cfgf; cfgf=$(mktemp); chmod 600 "$cfgf"
        printf 'header = "Authorization: Bearer %s"\n' "$tok" > "$cfgf"
        curl -s --config "$cfgf" "http://${host}:8900/api/status" \
          | python3 -m json.tool 2>/dev/null || warn "API did not respond"
        rm -f "$cfgf"
        pause ;;
      6)
        echo "  1) 127.0.0.1 (loopback only)"
        echo "  2) 0.0.0.0 (all interfaces, WARNING)"
        read -rp "Choice: " b
        case "$b" in
          1) echo "127.0.0.1" > "$API_HOST_CFG"; ok "Set to 127.0.0.1" ;;
          2) echo "0.0.0.0" > "$API_HOST_CFG"
             warn "0.0.0.0 exposes the API. Use firewall + strong token."
             read -rp "Continue? (yes): " y
             [[ "$y" != "yes" ]] && echo "127.0.0.1" > "$API_HOST_CFG" ;;
        esac
        read -rp "Restart API now? (y/N): " r
        [[ "${r,,}" == "y" ]] && { "$(xp_bin)" api stop; "$(xp_bin)" api start --host "$(cat "$API_HOST_CFG")"; }
        pause ;;
      0) return ;;
    esac
  done
}

net_optimize_apply() {
  need_root || return
  clear
  printf '%b\n' "${W}=== Apply Network Optimization ===${N}"
  echo
  echo "This will write kernel network tuning to:"
  echo "  ${C}${SYSCTL_CFG}${N}"
  echo
  echo "Settings:"
  echo "  - TCP congestion control: BBR + fq qdisc"
  echo "  - Buffers: kernel autotuning (no hard cap)"
  echo "  - somaxconn / syn_backlog: 65535"
  echo "  - tcp_tw_reuse: 1"
  echo "  - ip_local_port_range: 1024-65535"
  echo "  - tcp_mtu_probing: 1"
  echo
  read -rp "Apply now? (yes): " y
  [[ "$y" != "yes" ]] && { warn "Cancelled."; pause; return; }
  mkdir -p "$(dirname "$SYSCTL_BACKUP")"
  if [[ -f "$SYSCTL_CFG" ]]; then
    cp -f "$SYSCTL_CFG" "${SYSCTL_BACKUP}.$(date +%Y%m%d-%H%M%S)"
    log "Backed up existing sysctl config."
  fi
  cat > "$SYSCTL_CFG" <<'SYSCTL_EOF'
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr

net.ipv4.tcp_rmem = 4096 87380 6291456
net.ipv4.tcp_wmem = 4096 65536 4194304

net.core.somaxconn = 65535
net.ipv4.tcp_max_syn_backlog = 65535

net.ipv4.tcp_tw_reuse = 1
net.ipv4.ip_local_port_range = 1024 65535
net.ipv4.tcp_mtu_probing = 1
SYSCTL_EOF
  if ! grep -qw bbr <(sysctl -n net.ipv4.tcp_available_congestion_control 2>/dev/null); then
    warn "BBR not available in this kernel. Skipping tcp_congestion_control."
    sed -i '/tcp_congestion_control = bbr/d' "$SYSCTL_CFG" 2>/dev/null
  fi
  if sysctl -p "$SYSCTL_CFG" >/dev/null 2>&1; then
    ok "Network optimization applied."
    echo
    echo "Current state:"
    printf "  %-30s %s\n" "tcp_congestion_control" "$(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null)"
    printf "  %-30s %s\n" "default_qdisc" "$(sysctl -n net.core.default_qdisc 2>/dev/null)"
    printf "  %-30s %s\n" "somaxconn" "$(sysctl -n net.core.somaxconn 2>/dev/null)"
    printf "  %-30s %s\n" "tcp_tw_reuse" "$(sysctl -n net.ipv4.tcp_tw_reuse 2>/dev/null)"
  else
    err "sysctl failed. Check kernel support for BBR (requires kernel 4.9+)."
  fi
  pause
}

