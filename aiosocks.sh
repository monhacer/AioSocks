backup_menu() {
  need_root || return
  while true; do
    clear
    printf '%b\n' "${W}=== Backup / Restore ===${N}"
    echo "  1) Backup configs"
    echo "  2) Restore latest backup"
    echo "  3) List backups"
    echo "  0) Back"
    read -rp "Choice: " c
    mkdir -p "$BACKUP_DIR"
    case "$c" in
      1)
        local ts; ts=$(date +%Y%m%d-%H%M%S)
        if [[ -d "$CONF_DIR" ]]; then
          tar -czf "$BACKUP_DIR/psiphon-configs-$ts.tar.gz" -C "$(dirname "$CONF_DIR")" "$(basename "$CONF_DIR")"
          ok "Backup: $BACKUP_DIR/psiphon-configs-$ts.tar.gz"
        else warn "Config directory not found"; fi
        pause ;;
      2)
        local last; last=$(ls -1t "$BACKUP_DIR"/psiphon-configs-*.tar.gz 2>/dev/null | head -n1)
        [[ -z "$last" ]] && { warn "No backups"; pause; continue; }
        read -rp "Restore from $(basename "$last")? (y/N): " r
        [[ "${r,,}" == "y" ]] && { tar -xzf "$last" -C "$(dirname "$CONF_DIR")"; ok "Restored."; }
        pause ;;
      3) ls -lh "$BACKUP_DIR" 2>/dev/null || warn "Empty"; pause ;;
      0) return ;;
    esac
  done
}

watchdog_menu() {
  need_root || return
  while true; do
    clear
    local enabled="disabled"
    systemctl is-enabled aiosocks-watchdog.timer >/dev/null 2>&1 && enabled="enabled"
    local interval="60" threshold="3"
    local probe="https://www.gstatic.com/generate_204" timeout="15"
    if [[ -f "$WATCHDOG_CFG" ]]; then
      source "$WATCHDOG_CFG"
      interval="${WATCHDOG_INTERVAL:-60}"; threshold="${FAIL_THRESHOLD:-3}"
      probe="${PROBE_URL:-https://www.gstatic.com/generate_204}"; timeout="${PROBE_TIMEOUT:-15}"
    fi
    printf '%b\n' "${W}=== Health Watchdog ===${N}"
    echo "  Status:         ${enabled}"
    echo "  Interval:       ${interval}s"
    echo "  Fail threshold: ${threshold}"
    echo "  Probe URL:      ${probe}"
    echo "  Probe timeout:  ${timeout}s"
    echo
    echo "  1) Enable watchdog (global)"
    echo "  2) Disable watchdog (global)"
    echo "  3) Configure (global)"
    echo "  4) Run one-shot check"
    echo "  5) Show global log"
    echo "  6) Watchdog status / recent log"
    echo "  7) Show saved state (nodes restored at boot)"
    echo "  0) Back"
    read -rp "  Choice: " c
    case "$c" in
      1) ensure_watchdog_running; ok "Enabled."; pause ;;
      2) systemctl disable --now aiosocks-watchdog.timer 2>/dev/null; ok "Disabled."; pause ;;
      3)
        read -rp "Interval seconds [${interval}]: " i; [[ -n "$i" ]] && interval="$i"
        read -rp "Fail threshold [${threshold}]: " t; [[ -n "$t" ]] && threshold="$t"
        read -rp "Probe URL [${probe}]: " p; [[ -n "$p" ]] && probe="$p"
        read -rp "Probe timeout [${timeout}]: " o; [[ -n "$o" ]] && timeout="$o"
        cat > "$WATCHDOG_CFG" <<CFG_EOF
WATCHDOG_INTERVAL=$interval
FAIL_THRESHOLD=$threshold
PROBE_URL="$probe"
PROBE_TIMEOUT=$timeout
CFG_EOF
        ok "Saved."
        systemctl is-enabled aiosocks-watchdog.timer >/dev/null 2>&1 && {
          write_watchdog_units
          systemctl restart aiosocks-watchdog.timer
          ok "Restarted."
        }
        pause ;;
      4)
        [[ -x "$WATCHDOG_BIN" ]] && { "$WATCHDOG_BIN"; tail -n 20 /var/log/aiosocks-watchdog.log 2>/dev/null; } || warn "Not installed"
        pause ;;
      5) [[ -f /var/log/aiosocks-watchdog.log ]] && tail -n 50 /var/log/aiosocks-watchdog.log || warn "No log yet"; pause ;;
      6) list_healthchecks ;;
      7)
        clear
        printf '%b\n' "${W}=== Saved State (restored at boot) ===${N}"
        echo
        if [[ -f "$STATE_FILE" && -s "$STATE_FILE" ]]; then
          while IFS= read -r code; do
            [[ -z "$code" ]] && continue
            printf "  %s\n" "$code"
          done < "$STATE_FILE"
        else
          warn "No saved state."
        fi
        pause ;;
      0) return ;;
    esac
  done
}

main_menu() {
  while true; do
    banner
    if have_aio; then
      local wd_state="${D}off${N}"
      systemctl is-enabled aiosocks-watchdog.timer >/dev/null 2>&1 && wd_state="${G}on${N}"
      local bind_host="127.0.0.1"
      [[ -f "$API_HOST_CFG" ]] && bind_host=$(cat "$API_HOST_CFG")
      local net_state="${D}off${N}"
      [[ -f "$SYSCTL_CFG" ]] && net_state="${G}on${N}"
      local running=0
      for code in "${!SOCKS_PORT[@]}"; do is_running "$code" && running=$((running + 1)); done
      printf '%b\n' "  ${G}Installed${N} - ${W}$(core_version)${N}"
      printf '%b\n' "  Running nodes: ${G}${running}${N}   Watchdog: ${wd_state}   Net-opt: ${net_state}   API bind: ${bind_host}"
    else
      printf '%b\n' "  ${R}NOT INSTALLED${N}"
    fi
    echo
    printf '%b\n' "  ${W}[1]${N} Tunnel Control"
    printf '%b\n' "  ${W}[2]${N} Node Management"
    printf '%b\n' "  ${W}[3]${N} Monitoring"
    printf '%b\n' "  ${W}[4]${N} HTTP API"
    printf '%b\n' "  ${W}[5]${N} Health Watchdog"
    printf '%b\n' "  ${W}[6]${N} Network Optimization"
    printf '%b\n' "  ${W}[7]${N} Settings & Maintenance"
    printf '%b\n' "  ${W}[8]${N} ${R}Full Purge${N}"
    printf '%b\n' "  ${W}[0]${N} Exit"
    echo
    read -rp "  Your choice: " ch
    case "$ch" in
      1) tunnel_control_menu ;;
      2) node_management_menu ;;
      3) monitoring_menu ;;
      4) api_menu ;;
      5) watchdog_menu ;;
      6) net_optimize_menu ;;
      7) settings_menu ;;
      8) full_purge ;;
      0) echo "Goodbye."; exit 0 ;;
      *) warn "Invalid choice"; sleep 1 ;;
    esac
  done
}

