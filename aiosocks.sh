node_detail_menu() {
  local code="$1"
  while true; do
    clear
    local name="${COUNTRY_NAME[$code]:-$code}"
    local sp="${SOCKS_PORT[$code]:-?}"
    local hp="${HTTP_PORT[$code]:-?}"
    local badge ip_text
    if is_running "$code"; then
      badge="${BG_G}${W} RUNNING ${N}"
      ip_text=$(get_node_ip "$code")
    else
      badge="${BG_R}${W} STOPPED ${N}"
      ip_text="-"
    fi
    printf '%b\n' "${M}╔══════════════════════════════════════════════════════════╗${N}"
    printf '%b\n' "${M}║${N}  ${W}${code}${N}  ${D}—${N}  ${C}${name}${N}"
    printf '%b\n' "${M}╠══════════════════════════════════════════════════════════╣${N}"
    printf '%b\n' "${M}║${N}  Status  : ${badge}"
    printf '%b\n' "${M}║${N}  SOCKS   : ${C}127.0.0.1:${sp}${N}"
    printf '%b\n' "${M}║${N}  HTTP    : ${C}127.0.0.1:${hp}${N}"
    printf '%b\n' "${M}║${N}  Exit IP : ${C}${ip_text}${N}"
    printf '%b\n' "${M}╚══════════════════════════════════════════════════════════╝${N}"
    echo
    printf '%b\n' "  ${G}[1]${N} Start          ${G}[2]${N} Stop           ${G}[3]${N} Restart"
    printf '%b\n' "  ${G}[4]${N} SOCKS port     ${G}[5]${N} HTTP port      ${G}[6]${N} Both ports"
    printf '%b\n' "  ${G}[7]${N} Log tail       ${G}[8]${N} Log live       ${G}[9]${N} Speed test"
    printf '%b\n' "  ${G}[10]${N} Config file   ${G}[11]${N} Delete node    ${G}[12]${N} Rotate IP"
    printf '%b\n' "  ${G}[0]${N} Back"
    echo
    read -rp "  Choice: " c
    case "$c" in
      1)
        "$(xp_bin)" start "$code" && {
          ok "Started ${code}."
          sleep 2; add_state "$code"; ensure_watchdog_running
        }
        pause ;;
      2)
        "$(xp_bin)" stop "$code" && {
          ok "Stopped ${code}."
          remove_state "$code"
        }
        pause ;;
      3)
        "$(xp_bin)" restart "$code" && {
          ok "Restarted ${code}."
          sleep 2; add_state "$code"; ensure_watchdog_running
        }
        pause ;;
      4)
        read -rp "New SOCKS port for ${code} [${sp}]: " p
        [[ -z "$p" ]] && { pause; continue; }
        if "$(xp_bin)" port "$code" --socks "$p"; then
          SOCKS_PORT[$code]="$p"; write_port_map
          ok "SOCKS port updated to ${p}."
          read -rp "Restart to apply? (y/N): " r
          [[ "${r,,}" == "y" ]] && "$(xp_bin)" restart "$code"
        else err "Port change failed."; fi
        pause ;;
      5)
        read -rp "New HTTP port for ${code} [${hp}]: " p
        [[ -z "$p" ]] && { pause; continue; }
        if "$(xp_bin)" port "$code" --http "$p"; then
          HTTP_PORT[$code]="$p"; write_port_map
          ok "HTTP port updated to ${p}."
          read -rp "Restart to apply? (y/N): " r
          [[ "${r,,}" == "y" ]] && "$(xp_bin)" restart "$code"
        else err "Port change failed."; fi
        pause ;;
      6)
        read -rp "New SOCKS port [${sp}]: " sp2
        read -rp "New HTTP port [${hp}]: " hp2
        local args=()
        [[ -n "$sp2" ]] && args+=(--socks "$sp2")
        [[ -n "$hp2" ]] && args+=(--http "$hp2")
        [[ ${#args[@]} -eq 0 ]] && { warn "No change"; pause; continue; }
        if "$(xp_bin)" port "$code" "${args[@]}"; then
          [[ -n "$sp2" ]] && SOCKS_PORT[$code]="$sp2"
          [[ -n "$hp2" ]] && HTTP_PORT[$code]="$hp2"
          write_port_map
          ok "Ports updated."
          read -rp "Restart to apply? (y/N): " r
          [[ "${r,,}" == "y" ]] && "$(xp_bin)" restart "$code"
        else err "Port change failed."; fi
        pause ;;
      7) "$(xp_bin)" logs "$code" ; pause ;;
      8) "$(xp_bin)" logs "$code" -f ;;
      9) "$(xp_bin)" test "$code" ; pause ;;
      10)
        local f="${CONF_DIR}/psiphon.${code}.config"
        if [[ -f "$f" ]]; then
          printf '%b\n' "${W}--- ${f} ---${N}"
          cat "$f"
        else warn "Config file not found: $f"; fi
        pause ;;
      11)
        local f="${CONF_DIR}/psiphon.${code}.config"
        warn "This deletes the config file for ${code}."
        read -rp "Type DELETE to confirm: " y
        if [[ "$y" == "DELETE" ]]; then
          "$(xp_bin)" stop "$code" 2>/dev/null
          [[ -f "$f" ]] && rm -f "$f" && ok "Config deleted."
          remove_state "$code"
        else warn "Cancelled."; fi
        pause ;;
      12) rotate_node_ip "$code" ; pause ;;
      0) return ;;
    esac
  done
}

