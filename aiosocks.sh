        pause
      fi ;;
    2)
      shopt -s nullglob
      for f in "$LOG_DIR"/psiphon.*.log; do
        printf '%b\n' "\n${C}--- $(basename "$f") ---${N}"
        tail -n 30 "$f"
      done
      shopt -u nullglob
      pause ;;
  esac
}

show_status() {
  have_aio || { err "AioSocks is not installed"; pause; return; }
  clear
  printf '%b\n' "${M}╔══════════════════════════════════════════════════════════════════════════════════╗${N}"
  printf '%b\n' "${M}║${N}  ${W}SYSTEM STATUS${N}"
  printf '%b\n' "${M}╚══════════════════════════════════════════════════════════════════════════════════╝${N}"
  echo
  printf '%b\n' "${W}  NODES${N}"
  printf '%b\n' "${D}  ────────────────────────────────────────────────────────────────────────────────${N}"
  printf "  %-5s %-18s %-9s %-8s %-8s %-16s\n" "CODE" "COUNTRY" "STATUS" "SOCKS" "HTTP" "EXIT IP"
  local total=0 running=0
  for code in "${!SOCKS_PORT[@]}"; do
    total=$((total + 1))
    local st sc ip=""
    if is_running "$code"; then
      st="UP"; sc="${G}"; running=$((running + 1))
      ip=$(get_node_ip "$code")
    else
      st="DOWN"; sc="${D}"; ip="-"
    fi
    printf "  %-5s %-18s %b%-9s%b %-8s %-8s ${C}%-16s${N}\n" \
      "$code" "${COUNTRY_NAME[$code]:-$code}" "$sc" "$st" "$N" \
      "${SOCKS_PORT[$code]}" "${HTTP_PORT[$code]}" "$ip"
  done
  echo
  printf '%b\n' "${W}  PROCESSES${N}"
  printf '%b\n' "${D}  ────────────────────────────────────────────────────────────────────────────────${N}"
  local pids; pids=$(pgrep -f psiphon-tunnel-core 2>/dev/null)
  if [[ -z "$pids" ]]; then
    printf '%b\n' "  ${D}No tunnel processes running.${N}"
  else
    printf "  %-8s %-6s %-6s %-10s %s\n" "PID" "CPU%" "MEM%" "RSS" "CMD"
    ps -o pid,pcpu,pmem,rss,args -p $(echo "$pids" | paste -sd, -) 2>/dev/null \
      | tail -n +2 | awk '{printf "  %-8s %-6s %-6s %-10s %s\n",$1,$2,$3,$4,$5}'
  fi
  echo
  printf '%b\n' "${W}  SUMMARY${N}"
  printf '%b\n' "${D}  ────────────────────────────────────────────────────────────────────────────────${N}"
  printf "  Total nodes: ${W}%d${N}    Running: ${G}%d${N}    Stopped: ${D}%d${N}\n" \
    "$total" "$running" "$((total - running))"
  pause
}

