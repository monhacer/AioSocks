[[ -f "$CFG" ]] && source "$CFG"
PROBE_URL="${PROBE_URL:-https://www.gstatic.com/generate_204}"
PROBE_TIMEOUT="${PROBE_TIMEOUT:-15}"
FAIL_THRESHOLD="${FAIL_THRESHOLD:-3}"
STATE_DIR="/run/aiosocks-watchdog"
mkdir -p "$STATE_DIR"
log() { echo "$(date '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"; }

declare -A SOCKS_PORTS=()
if [[ -f "$PORT_MAP" ]]; then
  source "$PORT_MAP"
  for c in "${!SOCKS_PORT[@]}"; do SOCKS_PORTS[$c]="${SOCKS_PORT[$c]}"; done
else
  SOCKS_PORTS=(
    [AUTO]=1080 [AT]=1081 [BE]=1082 [BG]=1083 [CA]=1084 [CH]=1085 [CZ]=1086
    [DE]=1087 [DK]=1088 [EE]=1089 [FI]=1090 [FR]=1091 [GB]=1092 [IN]=1093
    [IT]=1094 [JP]=1095 [NL]=1096 [NO]=1097 [PL]=1098 [RO]=1099 [SE]=1100
    [US]=1101 [AU]=1102 [ES]=1103 [ID]=1104 [IE]=1105 [LT]=1106 [RS]=1107 [SG]=1108
  )
fi

check_proxy() {
  curl -s -o /dev/null -w "%{http_code}" \
    --socks5-hostname "127.0.0.1:$1" \
    --max-time "$PROBE_TIMEOUT" "$PROBE_URL" 2>/dev/null
}

for code in "${!SOCKS_PORTS[@]}"; do
  port="${SOCKS_PORTS[$code]}"
  ss -tln 2>/dev/null | grep -q ":${port} " || continue
  http_code=$(check_proxy "$port")
  if [[ "$http_code" == "204" || "$http_code" == "200" ]]; then
    log "OK $code (port $port) -> $http_code"
    rm -f "$STATE_DIR/$code.fail"
  else
    fail_file="$STATE_DIR/$code.fail"
    count=0; [[ -f "$fail_file" ]] && count=$(cat "$fail_file")
    count=$((count + 1)); echo "$count" > "$fail_file"
    log "FAIL $code (port $port) -> ${http_code:-timeout} (attempt $count)"
    if (( count >= FAIL_THRESHOLD )); then
      log "RESTART $code after $count failures"
      "$XP" restart "$code" >> "$LOG" 2>&1
      rm -f "$fail_file"; sleep 5
    fi
  fi
done
WATCHDOG_EOF
  chmod +x "$WATCHDOG_BIN"
}

