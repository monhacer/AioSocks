full_purge() {
  need_root || return
  clear
  printf '%b\n' "${R}========================================================${N}"
  printf '%b\n' "${R}                 FULL PURGE - AioSocks                 ${N}"
  printf '%b\n' "${R}========================================================${N}"
  echo
  warn "This will REMOVE:"
  echo "   - all AioSocks tunnels and services"
  echo "   - xp / aiosocks commands"
  echo "   - all configs under /etc/psiphon"
  echo "   - all logs, run files, backups"
  echo "   - watchdog service, timer, config and log"
  echo "   - boot restore service and state"
  echo "   - the AioSocks panel and dispatcher"
  echo "   - network optimization config (${SYSCTL_CFG})"
  echo
  read -rp "Type PURGE-ALL to confirm: " y
  [[ "$y" != "PURGE-ALL" ]] && { warn "Cancelled."; pause; return; }
  echo
  log "Stopping watchdog..."
  systemctl disable --now aiosocks-watchdog.timer 2>/dev/null
  systemctl stop aiosocks-watchdog.service 2>/dev/null
  rm -f "$WATCHDOG_SVC" "$WATCHDOG_TMR"
  systemctl daemon-reload 2>/dev/null
  log "Removing watchdog files..."
  rm -f "$WATCHDOG_BIN" "$WATCHDOG_CFG" /var/log/aiosocks-watchdog.log
  rm -rf /run/aiosocks-watchdog
  log "Removing legacy per-node health checks (if any)..."
  shopt -s nullglob
  for f in /etc/systemd/system/aiosocks-health-*.timer /etc/systemd/system/aiosocks-health-*.service; do
    local u; u=$(basename "$f")
    systemctl disable --now "$u" 2>/dev/null
  done
  shopt -u nullglob
  rm -f /etc/systemd/system/aiosocks-health-*.service
  rm -f /etc/systemd/system/aiosocks-health-*.timer
  rm -f /usr/local/bin/aiosocks-health-*
  rm -f /var/log/aiosocks-health-*.log
  rm -f /run/aiosocks-health-*.fail
  rm -f /run/aiosocks-health-*.retry
  log "Removing boot restore service..."
  systemctl disable --now aiosocks-restore.service 2>/dev/null
  rm -f "$RESTORE_SVC" "$RESTORE_BIN" /var/log/aiosocks-restore.log
  rm -f "$STATE_FILE"
  log "Removing network optimization config..."
  rm -f "$SYSCTL_CFG"
  systemctl daemon-reload 2>/dev/null
  log "Purging AioSocks core..."
  if have_aio; then
    "$(xp_bin)" uninstall --purge --yes 2>/dev/null || true
  fi
  log "Removing remaining directories..."
  rm -rf /etc/psiphon /var/log/xpsiphon /run/xpsiphon /tmp/psiphon
  rm -rf "$BACKUP_DIR"
  rm -f "$API_HOST_CFG" "$PORT_MAP_FILE"
  log "Removing commands..."
  rm -f /usr/local/bin/xp "$SHORT_BIN" "$PANEL_BIN"
  rm -rf /usr/local/lib/aiosocks
  rm -f /usr/local/bin/xpsiphon 2>/dev/null
  rm -f /etc/systemd/system/xpsiphon.service 2>/dev/null
  rm -f /etc/systemd/system/xpsiphon-api.service 2>/dev/null
  rm -f "$ROTATE_LOCK" 2>/dev/null
  systemctl daemon-reload 2>/dev/null
  systemctl reset-failed 2>/dev/null
  echo
  ok "Full purge complete. AioSocks has been removed from this system."
  sleep 3
  exit 0
}

