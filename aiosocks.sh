net_optimize_remove() {
  need_root || return
  clear
  printf '%b\n' "${W}=== Remove Network Optimization ===${N}"
  echo
  if [[ ! -f "$SYSCTL_CFG" ]]; then
    warn "No AioSocks sysctl config found."
    pause
    return
  fi
  warn "This removes ${SYSCTL_CFG}."
  read -rp "Continue? (yes): " y
  [[ "$y" != "yes" ]] && { warn "Cancelled."; pause; return; }
  rm -f "$SYSCTL_CFG"
  local latest
  latest=$(ls -1t "${SYSCTL_BACKUP}".* 2>/dev/null | head -n1)
  if [[ -n "$latest" ]]; then
    read -rp "Restore previous backup from $(basename "$latest")? (y/N): " r
    if [[ "${r,,}" == "y" ]]; then
      cp -f "$latest" "$SYSCTL_CFG"
      sysctl -p "$SYSCTL_CFG" >/dev/null 2>&1
      ok "Restored previous sysctl config."
    else
      ok "Config file removed. Kernel values remain until next reboot."
    fi
  else
    ok "Config file removed. Kernel values remain until next reboot."
  fi
  pause
}

