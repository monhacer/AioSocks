log()   { printf '%b\n' "${C}[*]${N} $*"; }
ok()    { printf '%b\n' "${G}[+]${N} $*"; }
warn()  { printf '%b\n' "${Y}[!]${N} $*"; }
err()   { printf '%b\n' "${R}[-]${N} $*"; }
info()  { printf '%b\n' "${B}[i]${N} $*"; }
pause() { echo; read -rp "Press Enter to return..."; }

need_root() {
  if [[ $EUID -ne 0 ]]; then
    err "This action requires root. Run with sudo."
    pause; return 1
  fi
}

have_aio() { [[ -x "$AIO_BIN" ]] || command -v xp >/dev/null 2>&1; }

# xp sometimes not on PATH (e.g. in early boot or different shell); fall back to binary path.
xp_bin() {
  if command -v xp >/dev/null 2>&1; then
    echo "xp"
  elif [[ -x "$AIO_BIN" ]]; then
    echo "$AIO_BIN"
  else
    echo "xp"
  fi
}

core_version() {
  local raw ver
  raw=$("$(xp_bin)" version 2>/dev/null | head -n1)
  ver=$(echo "$raw" | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n1)
  if [[ -n "$ver" ]]; then
    echo "AioSocks Core v${ver}"
  else
    echo "AioSocks Core"
  fi
}

