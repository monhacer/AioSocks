SHOW_IP_MODE="on"
SELECTED_CODES=()

prompt_countries_multi() {
  SELECTED_CODES=()
  clear
  local action_label="${1:-Select}"
  printf '%b\n' "${M}╔══════════════════════════════════════════════════════════════════════════════════╗${N}"
  printf '%b\n' "${M}║${N}  ${W}${action_label} Location(s)${N}                                                          ${M}║${N}"
  printf '%b\n' "${M}╚══════════════════════════════════════════════════════════════════════════════════╝${N}"
  echo
  printf '%b\n' "${D}  Enter one or more: numbers (1,3,5) or codes (US,DE,FR) or 'all'${N}"
  echo
  if [[ "$SHOW_IP_MODE" == "on" ]]; then
    printf "${W}%-5s %-9s %-5s %-18s %-7s %-7s %-16s${N}\n" \
      "#" "STATUS" "CODE" "COUNTRY" "SOCKS" "HTTP" "EXIT IP"
  else
    printf "${W}%-5s %-9s %-5s %-18s %-7s %-7s${N}\n" \
      "#" "STATUS" "CODE" "COUNTRY" "SOCKS" "HTTP"
  fi
  printf '%b\n' "${D}──────────────────────────────────────────────────────────────────────────────────${N}"
  local num=1
  local -a index=()
  for group in "${CONTINENTS[@]}"; do
    local continent="${group%%:*}"
    local codes="${group#*:}"
    [[ -z "${codes// /}" ]] && continue
    printf '%b\n' "${C}  ┌─ ${continent} ────────────────────────────────────────────────────────${N}"
    for code in $codes; do
      local st sc ip_str=""
      if is_running "$code"; then st="RUNNING"; sc="${G}"
      else st="STOPPED"; sc="${D}"; fi
      if [[ "$SHOW_IP_MODE" == "on" && "$st" == "RUNNING" ]]; then
        ip_str=$(get_node_ip "$code")
      elif [[ "$SHOW_IP_MODE" == "on" ]]; then
        ip_str="-"
      fi
      if [[ "$SHOW_IP_MODE" == "on" ]]; then
        printf " %-5s %b%-9s%b %-5s %-18s %-7s %-7s ${C}%-16s${N}\n" \
          "[$num]" "$sc" "$st" "$N" "$code" "${COUNTRY_NAME[$code]:-$code}" \
          "${SOCKS_PORT[$code]:-?}" "${HTTP_PORT[$code]:-?}" "$ip_str"
      else
        printf " %-5s %b%-9s%b %-5s %-18s %-7s %-7s\n" \
          "[$num]" "$sc" "$st" "$N" "$code" "${COUNTRY_NAME[$code]:-$code}" \
          "${SOCKS_PORT[$code]:-?}" "${HTTP_PORT[$code]:-?}"
      fi
      index[$num]="$code"
      num=$((num + 1))
    done
    echo
  done
  printf '%b\n' "${C}  ┌─ Special ───────────────────────────────────────────────────────────${N}"
  local st sc ip_str=""
  if is_running "AUTO"; then st="RUNNING"; sc="${G}"; else st="STOPPED"; sc="${D}"; fi
  if [[ "$SHOW_IP_MODE" == "on" && "$st" == "RUNNING" ]]; then
    ip_str=$(get_node_ip "AUTO")
  elif [[ "$SHOW_IP_MODE" == "on" ]]; then
    ip_str="-"
  fi
  if [[ "$SHOW_IP_MODE" == "on" ]]; then
    printf " %-5s %b%-9s%b %-5s %-18s %-7s %-7s ${C}%-16s${N}\n" \
      "[$num]" "$sc" "$st" "$N" "AUTO" "Automatic" \
      "${SOCKS_PORT[AUTO]}" "${HTTP_PORT[AUTO]}" "$ip_str"
  else
    printf " %-5s %b%-9s%b %-5s %-18s %-7s %-7s\n" \
      "[$num]" "$sc" "$st" "$N" "AUTO" "Automatic" \
      "${SOCKS_PORT[AUTO]}" "${HTTP_PORT[AUTO]}"
  fi
  index[$num]="AUTO"
  echo
  if [[ "$SHOW_IP_MODE" == "on" ]]; then
    printf '%b\n' "  ${D}IP mode: ON${N} ${D}(press 'i' to toggle)${N}    ${D}0) Back${N}"
  else
    printf '%b\n' "  ${D}IP mode: OFF${N} ${D}(press 'i' to toggle)${N}    ${D}0) Back${N}"
  fi
  echo
  local input
  read -rp "  Select: " input

  if [[ "${input,,}" == "i" ]]; then
    if [[ "$SHOW_IP_MODE" == "on" ]]; then SHOW_IP_MODE="off"; else SHOW_IP_MODE="on"; fi
    prompt_countries_multi "$action_label"
    return $?
  fi
  if [[ "$input" == "0" || -z "$input" ]]; then
    return 1
  fi
  if [[ "${input,,}" == "all" ]]; then
    local k
    for k in $(printf '%s\n' "${!index[@]}" | sort -n); do
      SELECTED_CODES+=("${index[$k]}")
    done
    return 0
  fi

  IFS=',' read -ra parts <<< "$input"
  for p in "${parts[@]}"; do
    p=$(echo "$p" | tr -d '[:space:]')
    [[ -z "$p" ]] && continue
    if [[ "$p" =~ ^[0-9]+$ ]]; then
      if [[ -n "${index[$p]}" ]]; then
        SELECTED_CODES+=("${index[$p]}")
      else
        warn "Number ${p} out of range"
      fi
    else
      local up="${p^^}"
      if [[ -n "${SOCKS_PORT[$up]}" ]]; then
        SELECTED_CODES+=("$up")
      else
        warn "Unknown code: ${p}"
      fi
    fi
  done

  if [[ ${#SELECTED_CODES[@]} -eq 0 ]]; then
    warn "No valid selection"
    sleep 1
    return 2
  fi

  local -a uniq=()
  local -A seen=()
  for c in "${SELECTED_CODES[@]}"; do
    if [[ -z "${seen[$c]}" ]]; then
      uniq+=("$c")
      seen[$c]=1
    fi
  done
  SELECTED_CODES=("${uniq[@]}")
  return 0
}

install_aio() {
  need_root || return 1
  log "Installing AioSocks from official source..."
  if ! command -v curl >/dev/null 2>&1; then
    log "Installing curl..."
    (apt-get update -qq && apt-get install -y -qq curl ca-certificates) || {
      err "Failed to install prerequisites"; pause; return 1; }
  fi
  if bash <(curl -fsSL "$INSTALL_URL"); then
    ok "Installation complete."
    have_aio && core_version
    write_port_map
    return 0
  else
    err "Installation failed."
    return 1
  fi
}

first_run_install() {
  banner
  printf '%b\n' "  ${Y}AioSocks is not installed yet.${N}"
  printf '%b\n' "  ${D}Starting automatic first-time installation...${N}"
  echo
  if install_aio; then
    ok "First-time setup complete."
    ensure_boot_restore
    sleep 2
  else
    err "Setup failed. Please check your network or try again."
    pause
    exit 1
  fi
}

# --- Self install: panel + wrapper ---
# Layout after install:
#   /usr/local/bin/xp                  -> real xPsiphon CLI (installed by upstream)
#   /usr/local/lib/aiosocks/aiosocks.sh -> this script
#   /usr/local/bin/aiosocks-panel       -> wrapper that execs the lib script
#   /usr/local/bin/aiosocks             -> dispatcher: no args -> panel, args -> xp
#
# So `aiosocks` (no args) opens the panel, `aiosocks status` calls xp.
install_short_command() {
  [[ $EUID -ne 0 ]] && return 0

  mkdir -p /usr/local/lib/aiosocks

  # Normalize both paths (resolve symlinks) before comparing.
  local src_real dst_real
  src_real=$(readlink -f "$SELF_SRC" 2>/dev/null || echo "$SELF_SRC")
  dst_real=$(readlink -f "$PANEL_LIB" 2>/dev/null || echo "$PANEL_LIB")

  # If we are already running from the lib file, skip the copy entirely.
  if [[ "$src_real" == "$dst_real" ]]; then
    :
  elif [[ -f "$SELF_SRC" && "$SELF_SRC" != /dev/fd/* && "$SELF_SRC" != /proc/*/fd/* ]]; then
    install -m 0755 "$SELF_SRC" "$PANEL_LIB" 2>/dev/null || cp -f "$SELF_SRC" "$PANEL_LIB"
  elif [[ -r "/proc/$$/fd/255" ]]; then
    cat "/proc/$$/fd/255" > "$PANEL_LIB" 2>/dev/null || true
  fi

  if [[ ! -s "$PANEL_LIB" ]]; then
    warn "Cannot self-install while running from a pipe."
    warn "To install the commands, run from a file:"
    warn "  curl -o aiosocks.sh <url> && sudo bash aiosocks.sh"
    return 0
  fi
  chmod 0755 "$PANEL_LIB"

  cat > "$PANEL_BIN" <<'PANEL_EOF'
#!/usr/bin/env bash
exec bash /usr/local/lib/aiosocks/aiosocks.sh "$@"
PANEL_EOF
  chmod 0755 "$PANEL_BIN"

  cat > "$SHORT_BIN" <<'DISPATCH_EOF'
#!/usr/bin/env bash
if [[ $# -eq 0 ]]; then
  exec /usr/local/bin/aiosocks-panel
fi
if command -v xp >/dev/null 2>&1; then
  exec xp "$@"
fi
if [[ -x /usr/local/bin/xp ]]; then
  exec /usr/local/bin/xp "$@"
fi
echo "aiosocks: 'xp' is not installed. Open the panel with: aiosocks" >&2
exit 127
DISPATCH_EOF
  chmod 0755 "$SHORT_BIN"
}

ensure_short_command() {
  [[ $EUID -eq 0 ]] && install_short_command
}

