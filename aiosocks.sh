tunnel_control_menu() {
  while true; do
    need_root || return
    have_aio || { err "AioSocks is not installed"; pause; return; }
    clear
    printf '%b\n' "${M}╔═══════════════════════════════════════════╗${N}"
    printf '%b\n' "${M}║${N}  ${W}TUNNEL CONTROL${N}                           ${M}║${N}"
    printf '%b\n' "${M}╚═══════════════════════════════════════════╝${N}"
    echo
    printf '%b\n' "  ${W}[1]${N} Start location(s)"
    printf '%b\n' "  ${W}[2]${N} Stop location(s)"
    printf '%b\n' "  ${W}[3]${N} Restart location(s)"
    printf '%b\n' "  ${W}[4]${N} Start all locations"
    printf '%b\n' "  ${W}[5]${N} Stop all locations"
    printf '%b\n' "  ${W}[6]${N} Restart all locations"
    printf '%b\n' "  ${W}[7]${N} Rotate IP of location(s)"
    printf '%b\n' "  ${W}[8]${N} Rotate IPs of all running locations"
    printf '%b\n' "  ${W}[0]${N} Back"
    echo
    read -rp "  Choice: " c
    case "$c" in
      1|2|3|7)
        local label action
        case "$c" in
          1) label="Start";     action=start   ;;
          2) label="Stop";      action=stop    ;;
          3) label="Restart";   action=restart ;;
          7) label="Rotate IP"; action=rotate  ;;
        esac
        prompt_countries_multi "$label"
        local rc=$?
        if [[ $rc -eq 1 ]]; then continue; fi
        if [[ $rc -eq 2 ]]; then pause; continue; fi
        local ok_count=0 fail_count=0 started_any=0
        for code in "${SELECTED_CODES[@]}"; do
          if [[ "$action" == "rotate" ]]; then
            if rotate_node_ip "$code"; then
              ok_count=$((ok_count+1))
            else
              fail_count=$((fail_count+1))
            fi
          else
            if "$(xp_bin)" "$action" "$code"; then
              ok "${label}ed ${code} (${COUNTRY_NAME[$code]:-$code})."
              ok_count=$((ok_count+1))
              case "$action" in
                start|restart)
                  sleep 2
                  add_state "$code"
                  started_any=1
                  ;;
                stop)
                  remove_state "$code"
                  ;;
              esac
            else
              err "${label} failed on ${code}."
              fail_count=$((fail_count+1))
            fi
          fi
        done
        (( started_any )) && ensure_watchdog_running
        printf '%b\n' "${W}Summary:${N} ${G}${ok_count} succeeded${N}, ${R}${fail_count} failed${N}"
        pause
        ;;
      4)
        "$(xp_bin)" start all && {
          ok "All locations started."
          sleep 2
          local started=0
          for code in "${!SOCKS_PORT[@]}"; do
            if is_running "$code"; then
              add_state "$code"
              started=1
            fi
          done
          (( started )) && ensure_watchdog_running
        }
        pause ;;
      5)
        "$(xp_bin)" stop all && {
          ok "All locations stopped."
          for code in "${!SOCKS_PORT[@]}"; do
            remove_state "$code"
          done
        }
        pause ;;
      6)
        "$(xp_bin)" restart all && {
          ok "All locations restarted."
          sleep 2
          save_running_state
          ensure_watchdog_running
        }
        pause ;;
      8) rotate_all_ips ; pause ;;
      0) return ;;
    esac
  done
}

