write_port_map() {
  local out="$PORT_MAP_FILE" c
  {
    echo "# auto-generated by aiosocks - do not edit"
    for c in "${!SOCKS_PORT[@]}"; do
      printf 'SOCKS_PORT[%s]=%s\n' "$c" "${SOCKS_PORT[$c]}"
    done
    for c in "${!HTTP_PORT[@]}"; do
      printf 'HTTP_PORT[%s]=%s\n' "$c" "${HTTP_PORT[$c]}"
    done
  } > "$out.tmp" 2>/dev/null && mv -f "$out.tmp" "$out"
}

is_running() {
  local port="${SOCKS_PORT[$1]:-}"
  [[ -z "$port" ]] && return 1
  if command -v ss >/dev/null 2>&1; then
    ss -tln 2>/dev/null | grep -q ":${port} "
  else
    netstat -tln 2>/dev/null | awk -v p=":${port} " '$4 ~ p {f=1} END{exit !f}'
  fi
}

get_node_ip() {
  local code="$1"
  local port="${SOCKS_PORT[$code]}"
  [[ -z "$port" ]] && { echo "-"; return 1; }
  local ip
  ip=$(curl -s -4 --max-time 8 --socks5-hostname "127.0.0.1:${port}" \
    https://api.ipify.org 2>/dev/null)
  if [[ -n "$ip" && "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "$ip"; return 0
  fi
  ip=$(curl -s -4 --max-time 8 --socks5-hostname "127.0.0.1:${port}" \
    https://ifconfig.co 2>/dev/null | tr -d '[:space:]')
  if [[ -n "$ip" && "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "$ip"
  else
    echo "unreachable"
  fi
}

rotate_node_ip() {
  local code="$1"
  local max_attempts="${2:-5}"
  local wait_secs="${3:-8}"

  if ! is_running "$code"; then
    warn "${code} is not running. Start it first."
    return 1
  fi

  local old_ip
  old_ip=$(get_node_ip "$code")
  info "Current IP for ${code}: ${C}${old_ip}${N}"
  info "Rotating IP (up to ${max_attempts} attempts)..."

  local attempt=1
  while (( attempt <= max_attempts )); do
    printf '%b\n' "  ${D}Attempt ${attempt}/${max_attempts}: restarting ${code}...${N}"
    "$(xp_bin)" restart "$code" >/dev/null 2>&1
    sleep "$wait_secs"

    local new_ip
    new_ip=$(get_node_ip "$code")

    if [[ -z "$new_ip" || "$new_ip" == "unreachable" || "$new_ip" == "-" ]]; then
      warn "  Attempt ${attempt}: tunnel not ready yet (${new_ip})"
      sleep 4
      attempt=$((attempt + 1))
      continue
    fi

    if [[ "$new_ip" != "$old_ip" ]]; then
      ok "  IP rotated: ${R}${old_ip}${N} ${D}->${N} ${G}${new_ip}${N}"
      return 0
    fi

    warn "  Attempt ${attempt}: same IP (${new_ip}), retrying..."
    attempt=$((attempt + 1))
  done

  err "Could not obtain a different IP after ${max_attempts} attempts."
  err "Psiphon may be reusing the same egress server. Try again later."
  return 1
}

rotate_all_ips() {
  exec 9>"$ROTATE_LOCK" || { err "Cannot open lock file."; return 1; }
  if ! flock -n 9; then
    warn "Rotation already running in another instance."
    exec 9>&-
    return 1
  fi
  local running_codes=()
  for code in "${!SOCKS_PORT[@]}"; do
    is_running "$code" && running_codes+=("$code")
  done
  if [[ ${#running_codes[@]} -eq 0 ]]; then
    warn "No running locations found."
    exec 9>&-
    return 1
  fi
  info "Rotating IPs for ${#running_codes[@]} running location(s)..."
  local success=0 fail=0
  for code in "${running_codes[@]}"; do
    if rotate_node_ip "$code"; then
      success=$((success + 1))
    else
      fail=$((fail + 1))
    fi
    echo
  done
  printf '%b\n' "${W}Summary:${N} ${G}${success} rotated${N}, ${R}${fail} failed${N}"
  exec 9>&-
}

save_running_state() {
  local -a codes=()
  for code in "${!SOCKS_PORT[@]}"; do
    is_running "$code" && codes+=("$code")
  done
  if [[ ${#codes[@]} -eq 0 ]]; then
    : > "$STATE_FILE"
  else
    printf '%s\n' "${codes[@]}" > "$STATE_FILE"
  fi
}

add_state() {
  local code="$1"
  touch "$STATE_FILE"
  grep -qx "$code" "$STATE_FILE" 2>/dev/null || echo "$code" >> "$STATE_FILE"
}

remove_state() {
  local code="$1"
  [[ -f "$STATE_FILE" ]] || return 0
  grep -vx "$code" "$STATE_FILE" > "${STATE_FILE}.tmp" 2>/dev/null || true
  mv -f "${STATE_FILE}.tmp" "$STATE_FILE"
}

ensure_boot_restore() {
  need_root || return
  cat > "$RESTORE_BIN" <<'RESTORE_EOF'
#!/usr/bin/env bash
STATE_FILE="/etc/aiosocks-state"
XP="/usr/local/bin/xp"
LOG="/var/log/aiosocks-restore.log"

log() { echo "$(date '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"; }

[[ -f "$STATE_FILE" ]] || { log "no state file"; exit 0; }

for i in {1..30}; do
  [[ -x "$XP" ]] && break
  sleep 1
done

sleep 5

while IFS= read -r code; do
  [[ -z "$code" ]] && continue
  log "restoring $code"
  "$XP" start "$code" >> "$LOG" 2>&1
  sleep 2
done < "$STATE_FILE"

if systemctl list-unit-files aiosocks-watchdog.timer >/dev/null 2>&1; then
  systemctl enable --now aiosocks-watchdog.timer >/dev/null 2>&1 || true
fi

log "restore done"
RESTORE_EOF
  chmod +x "$RESTORE_BIN"

  cat > "$RESTORE_SVC" <<UNIT_EOF
[Unit]
Description=AioSocks restore previously-running nodes on boot
After=network-online.target xpsiphon.service
Wants=network-online.target
ConditionPathExists=${STATE_FILE}

[Service]
Type=oneshot
ExecStart=${RESTORE_BIN}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
UNIT_EOF
  systemctl daemon-reload
  systemctl enable aiosocks-restore.service >/dev/null 2>&1
}

