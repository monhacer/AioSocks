write_watchdog_bin() {
  need_root || return 1
  cat > "$WATCHDOG_BIN" <<'WATCHDOG_EOF'
#!/usr/bin/env bash
set -o pipefail
CFG="/etc/aiosocks-watchdog.conf"
LOG="/var/log/aiosocks-watchdog.log"
PORT_MAP="/etc/aiosocks-ports.env"
