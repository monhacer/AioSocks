[Install]
WantedBy=timers.target
UNIT_EOF
  systemctl daemon-reload
}

ensure_watchdog_installed() {
  need_root || return 1
  [[ -x "$WATCHDOG_BIN" ]] || write_watchdog_bin
  if [[ ! -f "$WATCHDOG_CFG" ]]; then
    cat > "$WATCHDOG_CFG" <<'CFG_EOF'
WATCHDOG_INTERVAL=60
FAIL_THRESHOLD=3
PROBE_URL="https://www.gstatic.com/generate_204"
PROBE_TIMEOUT=15
CFG_EOF
  fi
  if [[ ! -f "$WATCHDOG_SVC" || ! -f "$WATCHDOG_TMR" ]]; then
    write_watchdog_units
  fi
}

ensure_watchdog_running() {
  need_root || return 0
  ensure_watchdog_installed || return 1
  if ! systemctl is-enabled --quiet aiosocks-watchdog.timer 2>/dev/null; then
    systemctl enable aiosocks-watchdog.timer >/dev/null 2>&1 || true
  fi
  if ! systemctl is-active --quiet aiosocks-watchdog.timer 2>/dev/null; then
    systemctl start aiosocks-watchdog.timer >/dev/null 2>&1 || true
  fi
}

