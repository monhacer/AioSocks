      if [[ $rc -eq 2 ]]; then pause; return; fi
      if [[ ${#SELECTED_CODES[@]} -eq 1 ]]; then
        local choice="${SELECTED_CODES[0]}"
        read -rp "Follow live? (y/N): " f
        if [[ "${f,,}" == "y" ]]; then "$(xp_bin)" logs "$choice" -f; else "$(xp_bin)" logs "$choice"; pause; fi
      else
        for choice in "${SELECTED_CODES[@]}"; do
          printf '%b\n' "\n${C}--- ${choice} (${COUNTRY_NAME[$choice]:-$choice}) ---${N}"
